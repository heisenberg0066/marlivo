import { chromium } from 'playwright-core';
const base = process.env.BASE ?? 'http://localhost:4173/marlivo/';
const out = process.env.OUT ?? '/tmp/shots';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
const sizes = { phone: { width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true }, laptop: { width: 1366, height: 768 } };
const which = process.argv[2] ?? 'phone';
const ctx = await b.newContext({ viewport: { width: sizes[which].width, height: sizes[which].height }, deviceScaleFactor: sizes[which].deviceScaleFactor ?? 1, isMobile: !!sizes[which].isMobile, hasTouch: !!sizes[which].hasTouch });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push('pageerror ' + e.message));
p.on('console', (m) => { if (m.type() === 'error') errs.push('console ' + m.text()); });
await p.goto(base + '#/');
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/${which}-home.png` });
await p.goto(base + '#/howto'); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/${which}-howto.png` });
await p.goto(base + '#/practice'); await p.waitForTimeout(500);
await p.getByText('Sit down').click();
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/${which}-lobby.png` });
console.log(await p.evaluate(() => location.hash));
console.log(errs.join('\n'));
await b.close();
